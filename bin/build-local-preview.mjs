import { createRequire } from 'node:module';
import { existsSync } from 'node:fs';
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, '..');
const outputRoot = path.join(projectRoot, '_site');
const outputMarker = path.join(outputRoot, '.meshtastic-local-preview');
const toolModules = process.env.PREVIEW_NODE_MODULES;

if (!toolModules) {
  throw new Error('PREVIEW_NODE_MODULES is not set. Run bin/serve-local-preview.ps1.');
}

const toolRequire = createRequire(path.join(toolModules, '..', 'package.json'));
const { Liquid } = toolRequire('liquidjs');
const { marked } = toolRequire('marked');
const sass = toolRequire('sass');
const YAML = toolRequire('yaml');

const config = YAML.parse(await readFile(path.join(projectRoot, '_config.yml'), 'utf8'));
const baseUrl = `/${String(config.baseurl || '').replace(/^\/+|\/+$/g, '')}`.replace(/\/$/, '');
const siteOutputRoot = path.join(outputRoot, baseUrl.replace(/^\//, ''));

if (existsSync(outputRoot) && !existsSync(outputMarker)) {
  throw new Error(`Refusing to replace ${outputRoot}: it was not created by this preview builder.`);
}

await rm(outputRoot, { recursive: true, force: true });
await mkdir(siteOutputRoot, { recursive: true });
await writeFile(outputMarker, 'Generated by bin/build-local-preview.mjs\n', 'utf8');

const engine = new Liquid({
  root: [
    path.join(projectRoot, '_theme', '_includes'),
    path.join(projectRoot, '_theme', '_layouts'),
  ],
  extname: '.html',
  strictFilters: false,
  strictVariables: false,
});

engine.registerFilter('relative_url', value => {
  const input = String(value || '');
  if (/^(?:[a-z]+:)?\/\//i.test(input)) return input;
  const normalized = input.startsWith('/') ? input : `/${input}`;
  return `${baseUrl}${normalized}`.replace(/\/{2,}/g, '/');
});

function parseFrontMatter(source) {
  const match = source.match(/^---\s*\r?\n([\s\S]*?)\r?\n---\s*\r?\n?/);
  if (!match) return { data: {}, body: source };
  return {
    data: YAML.parse(match[1]) || {},
    body: source.slice(match[0].length),
  };
}

async function findMarkdownFiles(directory, relativeDirectory = '') {
  const results = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name === '_site' || entry.name === '_theme') continue;
    const relativePath = path.join(relativeDirectory, entry.name);
    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (['assets', 'bin', 'firmwares', 'flasher', 'PCB-Projects'].includes(entry.name) && !relativeDirectory) continue;
      results.push(...await findMarkdownFiles(absolutePath, relativePath));
    } else if (entry.isFile() && entry.name.endsWith('.md') && entry.name !== 'README.md') {
      results.push(relativePath);
    }
  }
  return results;
}

const layoutSource = (await readFile(path.join(projectRoot, '_theme', '_layouts', 'default.html'), 'utf8'))
  // LiquidJS does not accept Jekyll's filter chain inside this comparison.
  // Keeping the shopping-guide group open is equivalent for this preview page.
  .replace('{% if item.sublinks | where: "url", page.url | size > 0 %}open{% endif %}', 'open');
const markdownFiles = await findMarkdownFiles(projectRoot);

for (const relativePath of markdownFiles) {
  const source = await readFile(path.join(projectRoot, relativePath), 'utf8');
  const { data, body } = parseFrontMatter(source);
  const relativeWithoutExtension = relativePath.replace(/\.md$/i, '').replaceAll('\\', '/');
  const pageUrl = `/${relativeWithoutExtension}.html`;
  const page = {
    ...data,
    path: relativePath.replaceAll('\\', '/'),
    url: pageUrl,
    title: data.title || path.basename(relativeWithoutExtension),
  };
  const content = marked.parse(body, { gfm: true, breaks: false });
  const rendered = await engine.parseAndRender(layoutSource, { site: config, page, content });
  const htmlTarget = path.join(siteOutputRoot, `${relativeWithoutExtension}.html`);
  const extensionlessTarget = path.join(siteOutputRoot, relativeWithoutExtension);
  await mkdir(path.dirname(htmlTarget), { recursive: true });
  await writeFile(htmlTarget, rendered, 'utf8');
  await writeFile(extensionlessTarget, rendered, 'utf8');
}

const sassEntryPath = path.join(projectRoot, '_theme', 'assets', 'css', 'style.scss');
const sassEntry = (await readFile(sassEntryPath, 'utf8')).replace(/^---\s*\r?\n---\s*\r?\n?/, '');
const sassResult = sass.compileString(sassEntry, {
  loadPaths: [path.join(projectRoot, '_theme', '_sass')],
  style: 'expanded',
  url: new URL(`file:///${sassEntryPath.replaceAll('\\', '/')}`),
});
const cssTarget = path.join(siteOutputRoot, 'assets', 'css', 'style.css');
await mkdir(path.dirname(cssTarget), { recursive: true });
await writeFile(cssTarget, sassResult.css, 'utf8');

for (const assetDirectory of ['assets', 'firmwares']) {
  const source = path.join(projectRoot, assetDirectory);
  if (existsSync(source) && (await stat(source)).isDirectory()) {
    await cp(source, path.join(siteOutputRoot, assetDirectory), { recursive: true, force: true });
  }
}

console.log(`Built ${markdownFiles.length} pages in ${siteOutputRoot}`);
